def get_stage_at_date(stage_history, activity_date):
    """
    Determine which pipeline stage the deal was in at the given activity_date.
    Iterates stage_history and returns the last entry whose entered_at <= activity_date.
    If the activity predates all stage history entries, return the first stage.
    Returns the stage string, or None if stage_history is empty.
    """
    import datetime
    if isinstance(activity_date, str):
        activity_date = datetime.date.fromisoformat(activity_date[:10])

    if not stage_history:
        return None

    stage_at = None
    for entry in stage_history:
        entered = datetime.date.fromisoformat(entry["entered_at"][:10])
        if entered <= activity_date:
            stage_at = entry["stage"]

    if stage_at is None:
        # Activity predates all stage entries — use the first stage
        stage_at = stage_history[0]["stage"]

    return stage_at


def pick_template(rng, activity_type, stage=None, exclude_bodies=None):
    """
    Pick a {subject, body} template for the given activity_type and stage.
    If stage is provided and templates exist for it, use stage-aware templates.
    Otherwise fall back to flat BODIES/SUBJECTS.
    exclude_bodies: set of body strings to avoid (for deduplication).
    Returns (subject, body) tuple.
    """
    if exclude_bodies is None:
        exclude_bodies = set()

    stage_map = STAGE_TEMPLATES.get(stage, {})
    templates = stage_map.get(activity_type, [])

    if templates:
        # Try to find one whose body is not in exclude_bodies
        available = [t for t in templates if t["body"] not in exclude_bodies]
        if not available:
            available = templates  # fall back, allow duplicate
        t = rng.choice(available)
        return t["subject"], t["body"]
    else:
        # Fall back to flat lists — keep subject and body coupled via index
        subj_list = SUBJECTS.get(activity_type, SUBJECTS["note"])
        body_list = BODIES.get(activity_type, BODIES["note"])
        # Pair them by index (zip to shortest)
        pairs = list(zip(subj_list, body_list))
        available = [(s, b) for s, b in pairs if b not in exclude_bodies]
        if not available:
            available = pairs
        return rng.choice(available)


